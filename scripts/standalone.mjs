import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const dist = path.join(root,'dist');
const types={'.svg':'image/svg+xml','.png':'image/png','.webp':'image/webp','.ico':'image/x-icon','.jpg':'image/jpeg','.woff':'font/woff'};
const encode = async file => 'data:' + types[path.extname(file)] + ';base64,' + (await readFile(path.join(dist,file))).toString('base64');
let html=await readFile(path.join(dist,'index.html'),'utf8');
let css=await readFile(path.join(dist,'styles.css'),'utf8');
for(const match of [...css.matchAll(/url\(['"]?([^)'"\s]+)['"]?\)/g)]) if(!match[1].startsWith('data:')) css=css.replace(match[0],'url("'+await encode(match[1])+'")');
html=html.replace('<link rel="stylesheet" href="styles.css">',()=>'<style>'+css+'</style>');
html=html.replace(/<script src="(?:config|app)\.js" defer><\/script>\s*/g,'');
html=html.replace(/<source\s[^>]*>/g,'');
for(const file of new Set([...html.matchAll(/(?:src|href)="([^"#]+\.(?:svg|png|webp|ico))"/g)].map(m=>m[1]))) html=html.replaceAll('"'+file+'"','"'+await encode(file)+'"');
const scripts=(await readFile(path.join(dist,'config.js'),'utf8'))+'\n'+(await readFile(path.join(dist,'app.js'),'utf8'));
html=html.replace('</body>',()=>'<script>'+scripts.replace(/<\/script/gi,'<\\/script')+'</script>\n</body>');
for(const match of html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)) if(!match[1].includes('application/ld+json')) new vm.Script(match[2]);
await writeFile(path.join(root,'site-petshop.html'),html);
console.log('Arquivo único criado: site-petshop.html');
